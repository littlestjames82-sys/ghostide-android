#!/bin/bash
# Assemble a clean build root for GhostIDE Android
# (hardening plan item 7). Usage:
#   bash assemble_inputs.sh <target-dir>
# Copies the two repos plus every declared binary
# input into <target-dir>, writes INPUTS.sha256 over
# the binary inputs, and symlinks the pinned toolchain
# (SDK + JDK are versioned separately, see BUILDING.md).
# Build the result with:
#   GHOSTIDE_WS=<target-dir> bash <target-dir>/ghostide-apk-build/build.sh
set -e
SRC_WS=${GHOSTIDE_SRC_WS:-$HOME/workspace}
DST=${1:?usage: assemble_inputs.sh <target-dir>}
mkdir -p "$DST"

copy_tree() {  # $1 = relative tree under the workspace
  mkdir -p "$DST/$1"
  (cd "$SRC_WS/$1" && tar --exclude='out' \
      --exclude='__pycache__' --exclude='*.pyc' \
      --exclude='app/src/main/assets/www' \
      --exclude='app/src/main/assets/eco.zip' \
      --exclude='app/src/main/assets/pyhome.zip' \
      --exclude='app/src/main/assets/git-templates.zip' \
      --exclude='app/src/main/assets/refdocs.json' \
      -cf - .) | (cd "$DST/$1" && tar -xf -)
}
# www/, eco.zip, pyhome.zip, git-templates.zip and
# refdocs.json under assets are build.sh outputs, so
# they are excluded here and regenerated by the build.

copy_tree ghost-ide
copy_tree ghostide-apk-build

# Ecosystem bundle sources: the eco.zip step reads
# <tool>/src from the workspace root for each bundled
# package + the GhostSlice library.
TOOLS=$(python3 -c "
import sys; sys.path.insert(0, '$SRC_WS/ghost-ide/tools')
from eco_bundle_gate import BUNDLED, LIBRARY
print(' '.join(LIBRARY + BUNDLED))")
for t in $TOOLS; do
  mkdir -p "$DST/$t"
  (cd "$SRC_WS/$t" && tar --exclude='__pycache__' \
      --exclude='*.pyc' -cf - src) | (cd "$DST/$t" && tar -xf -)
done

# Native libraries (llama.cpp JNI bridge set).
mkdir -p "$DST/ghostbot/phone/native/libs"
cp -r "$SRC_WS/ghostbot/phone/native/libs/arm64-v8a" \
      "$DST/ghostbot/phone/native/libs/"

# Signing input: an existing keystore keeps update
# compatibility; a fresh one is generated by build.sh
# but will NOT install over previously signed builds.
mkdir -p "$DST/ghostide-apk" "$DST/your_files"
if [ -f "$SRC_WS/ghostide-apk/debug.keystore" ]; then
  cp "$SRC_WS/ghostide-apk/debug.keystore" "$DST/ghostide-apk/"
fi

# Toolchain: pinned separately (BUILDING.md), linked.
ln -sfn "$SRC_WS/android-sdk" "$DST/android-sdk"
ln -sfn "$SRC_WS/jdk17" "$DST/jdk17"

# Manifest of the binary inputs (not the toolchain,
# not the keystore file itself).
(cd "$DST" && {
  find ghostbot/phone/native/libs -type f | sort
  find ghostide-apk-build/python-runtime/stage -type f | sort
} | xargs sha256sum > INPUTS.sha256)
echo "clean root assembled at $DST"
echo "binary inputs hashed: $(wc -l < "$DST/INPUTS.sha256") files in INPUTS.sha256"
